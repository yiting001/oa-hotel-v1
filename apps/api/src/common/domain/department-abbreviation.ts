const FALLBACK_PREFIX = 'OA';

export function departmentNumberPrefix(departmentName: string | null | undefined): string {
  const name = (departmentName ?? '').trim();
  if (!name) return FALLBACK_PREFIX;
  const known = KNOWN_DEPARTMENT_PREFIXES[name];
  if (known) return known;

  const initials: string[] = [];
  for (const character of name) {
    if (/[A-Za-z0-9]/.test(character)) {
      initials.push(character.toUpperCase());
      continue;
    }
    if (/\s/.test(character)) continue;
    const initial = CHARACTER_INITIALS[character];
    if (!initial) return FALLBACK_PREFIX;
    initials.push(initial);
  }
  return initials.length > 0 ? initials.join('').slice(0, 8) : FALLBACK_PREFIX;
}
